def stability(key, dataset):
    """-> (TCPC, TOPC)"""
    i = DATASETS.index(dataset)
    row = TABLE2[key]
    return row[2 * i], row[2 * i + 1]


def ablation(pert, abl, dataset):
    i = DATASETS.index(dataset)
    row = TABLE3.get((pert, abl))
    return (row[2 * i], row[2 * i + 1]) if row else (None, None)
